/**
 * Polling change-detection comparator for the hybrid subscription manager.
 *
 * Naively comparing entities via serialized equality is correct but
 * O(size-of-entity) per poll. That falls apart for tables
 * holding large blobs — e.g. an `activities` row whose `output_data` carries
 * a multi-megabyte `Uint8ClampedArray`: each poll cycle (default 1 s) would
 * stringify ~16 MB per row × N rows, locking the main thread.
 *
 * Fast path: if both rows expose a string `updated_at`, compare just those.
 * The repositories in this codebase bump `updated_at` on every write (see
 * `ActivityRepository.updateActivity`), so the timestamp is a sufficient
 * change witness. Fall back to the structural compare for tables that don't
 * follow that convention so correctness is preserved everywhere.
 */
function compareEntitiesForChange<T>(a: T, b: T): boolean {
  const au = (a as { updated_at?: unknown })?.updated_at;
  const bu = (b as { updated_at?: unknown })?.updated_at;
  if (typeof au === "string" && typeof bu === "string") {
    return au === bu;
  }
  return deepEqual(a, b);
}

/**
 * A tabular repository implementation using IndexedDB for browser-based storage.
 *
 * @template Schema - The schema definition for the entity
 * @template PrimaryKeyNames - Array of property names that form the primary key
 */
export class IndexedDbTabularStorage<
  Schema extends DataPortSchemaObject,
  PrimaryKeyNames extends ReadonlyArray<keyof Schema["properties"]>,
  // computed types
  Entity = FromSchema<Schema, TypedArraySchemaOptions>,
  PrimaryKey = SimplifyPrimaryKey<Entity, PrimaryKeyNames>,
  Value = Omit<Entity, PrimaryKeyNames[number] & keyof Entity>,
  InsertType extends InsertEntity<Entity, AutoGeneratedKeys<Schema>> = InsertEntity<
    Entity,
    AutoGeneratedKeys<Schema>
  >,
> extends BaseTabularStorage<Schema, PrimaryKeyNames, Entity, PrimaryKey, Value, InsertType> {
  private db: IDBDatabase | undefined;
  /**
   * True between `setupDatabase`'s call to `applyTabularMigrations` and its
   * completion. Backfill ops inside the orchestrator may close `this.db`
   * (via `onversionchange` from the next migration's upgrade) and trigger
   * a re-entrant `setupDatabase` call from `getDb()`. The re-entrant call
   * must only re-open the IDB connection — it MUST NOT recurse into the
   * orchestrator, or migrations will be replayed mid-flight.
   */
  private applyingMigrations = false;
  private setupPromise: Promise<IDBDatabase> | null = null;
  private migrationOptions: MigrationOptions;
  private hybridManager: HybridSubscriptionManager<
    Entity,
    string,
    TabularChangePayload<Entity>
  > | null = null;
  private readonly hybridOptions: {
    readonly useBroadcastChannel: boolean;
    readonly backupPollingIntervalMs: number;
  };
  /**
   * Indexes safe for cursor-based narrowing. An IDB index excludes records
   * whose keyPath has any undefined component, and equally any null one (null
   * is not a valid key), so iterating an index can miss records when an indexed
   * column is optional in the schema or its type admits null. Native
   * `count(range)` and cursor scans are only correct over indexes whose every
   * column is required and non-nullable. Computed lazily on first use.
   */
  private cursorSafeIndexes: Array<Array<keyof Entity>> | undefined;

  /**
   * Creates a new IndexedDB-based tabular repository.
   * @param table - Name of the IndexedDB store to use.
   * @param schema - Schema defining the structure of the entity
   * @param primaryKeyNames - Array of property names that form the primary key
   * @param indexes - Array of columns or column arrays to make searchable. Each string or single column creates a single-column index,
   *                    while each array creates a compound index with columns in the specified order.
   * @param migrationOptions - Options for handling database schema migrations
   * @param clientProvidedKeys - How to handle client-provided values for auto-generated keys
   * @param tabularMigrations - Declarative migrations evolving the store schema
   * @param uniqueIndexes - Compound column tuples enforced as native IDB UNIQUE
   *                        indexes (`store.createIndex(..., { unique: true })`).
   *                        A `put` whose tuple collides with another record's
   *                        rejects with a `ConstraintError`.
   */
  constructor(
    public table: string = "tabular_store",
    schema: Schema,
    primaryKeyNames: PrimaryKeyNames,
    indexes: readonly (keyof NoInfer<Entity> | readonly (keyof NoInfer<Entity>)[])[] = [],
    migrationOptions: MigrationOptions & {
      readonly useBroadcastChannel?: boolean;
      readonly backupPollingIntervalMs?: number;
    } = {},
    clientProvidedKeys: ClientProvidedKeysOption = "if-missing",
    tabularMigrations?: ReadonlyArray<ITabularMigration>,
    uniqueIndexes: readonly (readonly (keyof NoInfer<Entity>)[])[] = []
  ) {
    super(
      schema,
      primaryKeyNames,
      indexes,
      clientProvidedKeys,
      tabularMigrations,
      table,
      uniqueIndexes
    );
    this.migrationOptions = migrationOptions;
    this.hybridOptions = {
      useBroadcastChannel: migrationOptions.useBroadcastChannel ?? true,
      backupPollingIntervalMs: migrationOptions.backupPollingIntervalMs ?? 5000,
    };
  }

  private async getDb(): Promise<IDBDatabase> {
    if (this.db) return this.db;
    await this.setupDatabase();
    return this.db!;
  }

  /**
   * Sets up the IndexedDB database table with the required schema and indexes.
   * Must be called before using any other methods.
   */
  public override async setupDatabase(): Promise<void> {
    if (this.db) return;
    if (this.setupPromise) {
      await this.setupPromise;
      return;
    }

    // Re-entrant guard: when called from inside an in-flight migration
    // (typically because a backfill's `getPage` hit a closed connection
    // after the previous migration's upgrade-tx version bump), only
    // re-open the IDB connection. Re-running `applyTabularMigrations`
    // here would replay the orchestrator and double-apply migrations.
    if (this.applyingMigrations) {
      this.setupPromise = this.performSetup();
      try {
        this.db = await this.setupPromise;
        this.rewireOnVersionChange();
      } finally {
        this.setupPromise = null;
      }
      return;
    }

    // Probe whether the object store already exists BEFORE performSetup
    // creates it. The orchestrator needs this signal to take the
    // mark-all-applied fast path on a brand-new DB; otherwise it would
    // see the (just-created) store and try to apply ops against the
    // already-current target schema.
    const freshTable =
      this.tabularMigrations && this.tabularMigrations.length > 0
        ? !(await this.probeObjectStoreExists())
        : false;

    this.setupPromise = this.performSetup();
    try {
      this.db = await this.setupPromise;
    } finally {
      this.setupPromise = null;
    }

    if (this.tabularMigrations && this.tabularMigrations.length > 0) {
      this.rewireOnVersionChange();
      this.applyingMigrations = true;
      try {
        await this.applyTabularMigrations({ freshTable });
      } finally {
        this.applyingMigrations = false;
      }
      // After migrations, this.db may be undefined (closed by onversionchange).
      // Reopen so the storage is ready for use.
      if (!this.db) {
        this.db = await this.performSetup();
      }
    }
  }

  /**
   * Wires `onversionchange` so that when the migration runner bumps the IDB
   * version (currentVersion + 1 to trigger onupgradeneeded), the current
   * open connection is both closed AND cleared from `this.db`. Without the
   * clear, getDb() would return a stale closed connection and throw
   * InvalidStateError on the next transaction attempt (e.g. during backfill).
   */
  private rewireOnVersionChange(): void {
    if (!this.db) return;
    this.db.onversionchange = () => {
      this.db?.close();
      this.db = undefined;
    };
  }

  /**
   * Read-only probe: does the object store already exist in the IDB
   * database? Used by `setupDatabase` to decide between the orchestrator's
   * fresh-DB fast path (mark-all-applied) and the run-pending path.
   * Delegates to the shared `idbObjectStoreExists` helper.
   */
  private async probeObjectStoreExists(): Promise<boolean> {
    return idbObjectStoreExists(this.table, this.table);
  }

  private async performSetup(): Promise<IDBDatabase> {
    const pkColumns = super.primaryKeyColumns() as string[];

    const expectedIndexes: ExpectedIndexDefinition[] = [];

    for (const spec of this.indexes) {
      const columns = spec as Array<keyof Entity>;
      // Skip if this is just the primary key or a prefix of it
      if (columns.length <= pkColumns.length) {
        const isPkPrefix = columns.every((col, idx) => col === pkColumns[idx]);
        if (isPkPrefix) continue;
      }

      const columnNames = columns.map((col) => String(col));
      const indexName = columnNames.join("_");
      expectedIndexes.push({
        name: indexName,
        keyPath: columnNames.length === 1 ? columnNames[0] : columnNames,
        options: { unique: false },
      });
    }

    // Declared unique tuples become native IDB UNIQUE indexes so a colliding
    // `put` is rejected with a `ConstraintError` — the browser-tier equivalent
    // of the `CREATE UNIQUE INDEX` the SQL backends emit. The base class has
    // already dropped any regular index whose tuple exactly matches a unique
    // tuple, so reusing the plain `cols.join("_")` name cannot collide; it also
    // lets the query planner narrow on the unique index (see
    // {@link getCursorSafeIndexes}). IDB excludes records with an
    // undefined/invalid keyPath component from an index, so NULL/undefined tuple
    // values never trip the constraint — matching SQL's "NULL is distinct".
    for (const columns of this.uniqueIndexes) {
      const columnNames = (columns as Array<keyof Entity>).map((col) => String(col));
      const indexName = columnNames.join("_");
      expectedIndexes.push({
        name: indexName,
        keyPath: columnNames.length === 1 ? columnNames[0] : columnNames,
        options: { unique: true },
      });
    }

    const primaryKey = pkColumns.length === 1 ? pkColumns[0] : pkColumns;

    // IndexedDB autoIncrement only works with single numeric keys
    const useAutoIncrement =
      this.hasAutoGeneratedKey() &&
      this.autoGeneratedKeyStrategy === "autoincrement" &&
      pkColumns.length === 1;

    return await ensureIndexedDbTable(
      this.table,
      primaryKey,
      expectedIndexes,
      this.migrationOptions,
      useAutoIncrement
    );
  }

  public override getMigrationApplier(): ITabularMigrationApplier | null {
    // The IDB tabular storage uses `this.table` as both the database name
    // and the object store name (see `ensureIndexedDbTable`'s call to
    // `openIdb(tableName, ...)`).
    return new IndexedDbTabularMigrationApplier(this.table, this.table, {
      getPage: (req) =>
        // The applier types `cursor` as `unknown` to avoid coupling to the
        // PageCursor branded type; cast at the boundary.
        this.getPage(req as Parameters<typeof this.getPage>[0]) as Promise<{
          items: Array<Record<string, unknown>>;
          nextCursor?: unknown;
        }>,
      put: (row) => this.put(row as Parameters<typeof this.put>[0]),
      delete: (row) => this.delete(row as Parameters<typeof this.delete>[0]),
    });
  }

  /**
   * Integer autoincrement keys are handled by IndexedDB's autoIncrement; this
   * only generates UUID keys client-side.
   */
  protected override generateKeyValue(
    columnName: string,
    strategy: KeyGenerationStrategy
  ): string | number {
    if (strategy === "uuid") {
      return uuid4();
    }
    throw new Error(
      `IndexedDB autoincrement keys are generated by the database, not client-side. Column: ${columnName}`
    );
  }

  /**
   * Resolve client-side key-generation policy for a single record and return
   * the entity the caller should hand to `store.put`. Shared by {@link put}
   * and {@link putBulkInTransaction} so the autoincrement / UUID /
   * clientProvidedKeys rules stay in one place.
   *
   * Throws synchronously on `clientProvidedKeys: "always"` without a key,
   * so the failure surfaces before any IDB transaction opens.
   */
  protected prepareRecordForPut(record: InsertType): Entity {
    let recordToStore = record as unknown as Entity;
    if (!this.hasAutoGeneratedKey() || !this.autoGeneratedKeyName) return recordToStore;

    const keyName = String(this.autoGeneratedKeyName);
    const clientProvidedValue = (record as Record<string, unknown>)[keyName];
    const hasClientValue = clientProvidedValue !== undefined && clientProvidedValue !== null;

    if (this.autoGeneratedKeyStrategy === "uuid") {
      let shouldGenerate = false;
      if (this.clientProvidedKeys === "never") {
        shouldGenerate = true;
      } else if (this.clientProvidedKeys === "always") {
        if (!hasClientValue) {
          throw new Error(
            `Auto-generated key "${keyName}" is required when clientProvidedKeys is "always"`
          );
        }
        shouldGenerate = false;
      } else {
        shouldGenerate = !hasClientValue;
      }

      if (shouldGenerate) {
        const generatedValue = this.generateKeyValue(keyName, "uuid");
        recordToStore = { ...record, [keyName]: generatedValue } as Entity;
      }
    } else if (this.autoGeneratedKeyStrategy === "autoincrement") {
      if (this.clientProvidedKeys === "always" && !hasClientValue) {
        throw new Error(
          `Auto-generated key "${keyName}" is required when clientProvidedKeys is "always"`
        );
      }
      if (this.clientProvidedKeys === "never") {
        const { [keyName]: _, ...rest } = record as Record<string, unknown>;
        recordToStore = rest as Entity;
      }
    }
    return recordToStore;
  }

  /**
   * @emits put - Emitted when the value is successfully stored
   */
  async put(record: InsertType): Promise<Entity> {
    const db = await this.getDb();
    let recordToStore = this.prepareRecordForPut(record);

    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readwrite");
      const store = transaction.objectStore(this.table);
      const request = store.put(recordToStore);
      request.onerror = () => {
        reject(request.error);
      };
      request.onsuccess = () => {
        if (
          this.hasAutoGeneratedKey() &&
          this.autoGeneratedKeyName &&
          this.autoGeneratedKeyStrategy === "autoincrement"
        ) {
          const keyName = String(this.autoGeneratedKeyName);
          if (recordToStore[keyName as keyof Entity] === undefined) {
            recordToStore = { ...recordToStore, [keyName]: request.result } as Entity;
          }
        }
        safeEmit(this.events, "put", recordToStore);
        resolve(recordToStore);
      };
      transaction.oncomplete = () => {
        this.hybridManager?.notifyLocalChange();
      };
    });
  }

  /**
   * @emits put - Emitted for each record successfully stored
   */
  async putBulk(records: InsertType[]): Promise<Entity[]> {
    return await this.putBulkInTransaction(records);
  }

  /**
   * Atomic batch put: stages every record into a single `readwrite`
   * transaction and only emits per-row `put` events after `tx.oncomplete`,
   * so a failure on any record aborts the whole batch and no subscriber
   * observes uncommitted rows. Used by vector storages (which need an
   * all-or-nothing guarantee for chunk ingestion) — the inherited
   * Promise.all-based `putBulk` opens one transaction per row and can
   * leave the store half-written if the second or later request errors.
   *
   * Per-row `put` events fire from `tx.oncomplete`, which means subscribers
   * to {@link put} see batched commits as a burst after the transaction
   * succeeds rather than interleaved with the IDB requests.
   *
   * Wraps the transaction-open in a single retry to absorb the
   * `InvalidStateError` that fires when an `onversionchange` close races a
   * brand-new transaction.
   */
  protected async putBulkInTransaction(records: InsertType[]): Promise<Entity[]> {
    if (records.length === 0) return [];
    const prepared = records.map((r) => this.prepareRecordForPut(r));

    const run = async (): Promise<Entity[]> => {
      const db = await this.getDb();
      return new Promise<Entity[]>((resolve, reject) => {
        let tx: IDBTransaction;
        try {
          tx = db.transaction(this.table, "readwrite");
        } catch (err) {
          reject(err);
          return;
        }
        const store = tx.objectStore(this.table);
        const results: Entity[] = new Array(prepared.length);
        const useAutoincrement =
          this.hasAutoGeneratedKey() &&
          this.autoGeneratedKeyName !== undefined &&
          this.autoGeneratedKeyStrategy === "autoincrement";
        const keyName = useAutoincrement ? String(this.autoGeneratedKeyName) : undefined;

        // Wire the transaction-level settlers BEFORE issuing any request so a
        // request that errors mid-batch (which aborts the whole transaction)
        // is always observed, regardless of how far the loop got.
        tx.oncomplete = () => {
          for (const r of results) safeEmit(this.events, "put", r);
          this.hybridManager?.notifyLocalChange();
          resolve(results);
        };
        tx.onerror = () => reject(tx.error);
        tx.onabort = () => reject(tx.error ?? new Error("putBulk transaction aborted"));

        try {
          for (let i = 0; i < prepared.length; i++) {
            const recordToStore = prepared[i];
            const request = store.put(recordToStore);
            // Capture the autoincrement key IDB assigned, so the
            // per-row result mirrors the single-`put` contract.
            request.onsuccess = () => {
              let finalRecord = recordToStore;
              if (useAutoincrement && keyName !== undefined) {
                if (finalRecord[keyName as keyof Entity] === undefined) {
                  finalRecord = { ...finalRecord, [keyName]: request.result } as Entity;
                }
              }
              results[i] = finalRecord;
            };
            // No-op request error handler: we deliberately do NOT call
            // `event.preventDefault()`, so the error still propagates and
            // aborts the whole transaction (settled via `tx.onabort`). The
            // handler only stops the IDB engine from reporting it as an
            // uncaught request error.
            request.onerror = () => {};
          }
        } catch (err) {
          // `store.put()` can throw synchronously — `DataError` on a value that
          // fails structured clone in a real browser, or `InvalidStateError`
          // when the connection is closing. Requests already issued in this
          // loop are live on the transaction, so abort it to keep the batch
          // all-or-nothing before surfacing the error (the caller retries the
          // `InvalidStateError` case against a fresh connection).
          try {
            tx.abort();
          } catch {
            // transaction may already be inactive / aborting
          }
          reject(err);
        }
      });
    };

    try {
      return await run();
    } catch (err) {
      // `InvalidStateError` fires when the IDB connection was closed under
      // us by an `onversionchange` (e.g. a migration in another tab bumped
      // the version). Drop the stale handle so `getDb()` re-opens, then
      // retry exactly once.
      if (err instanceof DOMException && err.name === "InvalidStateError") {
        // The first attempt's transaction never reached `tx.oncomplete` (where
        // per-row `put` events fire), so no committed row was visible. Do NOT
        // emit a `rollback` here: the retry below may succeed and commit the
        // whole batch, in which case a rollback event would falsely signal that
        // nothing landed. Only emit rollback if the retry itself fails.
        try {
          this.db?.close();
        } catch {
          // best-effort: connection may already be closed.
        }
        this.db = undefined;
        try {
          return await run();
        } catch (retryErr) {
          safeEmit(this.events, "rollback", {
            op: "putBulkInTransaction",
            error: retryErr,
            ids: [],
          });
          throw retryErr;
        }
      }
      safeEmit(this.events, "rollback", { op: "putBulkInTransaction", error: err, ids: [] });
      throw err;
    }
  }

  protected override getPrimaryKeyAsOrderedArray(key: PrimaryKey) {
    return super
      .getPrimaryKeyAsOrderedArray(key)
      .map((value) => (typeof value === "bigint" ? value.toString() : value));
  }

  private getIndexedKey(key: PrimaryKey): any {
    const keys = super
      .getPrimaryKeyAsOrderedArray(key)
      .map((value) => (typeof value === "bigint" ? value.toString() : value));
    return keys.length === 1 ? keys[0] : keys;
  }

  /**
   * @emits get - Emitted when the value is successfully retrieved
   */
  async get(key: PrimaryKey): Promise<Entity | undefined> {
    const db = await this.getDb();
    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readonly");
      const store = transaction.objectStore(this.table);
      const request = store.get(this.getIndexedKey(key));
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        if (!request.result) {
          safeEmit(this.events, "get", key, undefined);
          resolve(undefined);
          return;
        }
        safeEmit(this.events, "get", key, request.result);
        resolve(request.result);
      };
    });
  }

  async getAll(options?: QueryOptions<Entity>): Promise<Entity[] | undefined> {
    this.validateGetAllOptions(options);
    const db = await this.getDb();
    const transaction = db.transaction(this.table, "readonly");
    const store = transaction.objectStore(this.table);
    const request = store.getAll();
    return new Promise((resolve, reject) => {
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        let values: Entity[] = request.result;
        if (values.length === 0) {
          resolve(undefined);
          return;
        }

        if (options?.orderBy && options.orderBy.length > 0) {
          values.sort((a, b) => {
            for (const { column, direction } of options.orderBy!) {
              const aVal = a[column] as string | number | null | undefined;
              const bVal = b[column] as string | number | null | undefined;
              if (aVal == null && bVal == null) continue;
              if (aVal == null) return direction === "ASC" ? -1 : 1;
              if (bVal == null) return direction === "ASC" ? 1 : -1;
              if (aVal < bVal) return direction === "ASC" ? -1 : 1;
              if (aVal > bVal) return direction === "ASC" ? 1 : -1;
            }
            return 0;
          });
        }

        if (options?.offset !== undefined) {
          values = values.slice(options.offset);
        }

        if (options?.limit !== undefined) {
          values = values.slice(0, options.limit);
        }

        resolve(values.length > 0 ? values : undefined);
      };
    });
  }

  async delete(key: PrimaryKey): Promise<void> {
    const db = await this.getDb();
    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readwrite");
      const store = transaction.objectStore(this.table);
      const request = store.delete(this.getIndexedKey(key));
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        safeEmit(this.events, "delete", key as Partial<Entity>);
        resolve();
      };
      transaction.oncomplete = () => {
        this.hybridManager?.notifyLocalChange();
      };
    });
  }

  /**
   * @emits clearall - Emitted when all values are deleted
   */
  async deleteAll(): Promise<void> {
    const db = await this.getDb();
    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readwrite");
      const store = transaction.objectStore(this.table);
      const request = store.clear();
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        safeEmit(this.events, "clearall");
        resolve();
      };
      transaction.oncomplete = () => {
        this.hybridManager?.notifyLocalChange();
      };
    });
  }

  async size(): Promise<number> {
    const db = await this.getDb();
    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readonly");
      const store = transaction.objectStore(this.table);
      const request = store.count();
      request.onerror = () => reject(request.error);
      request.onsuccess = () => resolve(request.result);
    });
  }

  /**
   * Returns the subset of configured indexes safe to use for cursor-based
   * narrowing — those whose every column is required by the schema AND cannot
   * hold null. IDB excludes a record from an index when the keyPath component
   * is undefined, and equally when it is null (null is not a valid key), so
   * iterating an index would silently miss records for either shape.
   *
   * A required-but-nullable column is the second case: legal here, impossible
   * in SQL (a required column is emitted `NOT NULL`), and invisible to the
   * caller because the scan returns fewer rows rather than failing.
   */
  private getCursorSafeIndexes(): Array<Array<keyof Entity>> {
    if (this.cursorSafeIndexes) return this.cursorSafeIndexes;
    const required = new Set(this.schema.required ?? []);
    const properties = this.schema.properties as Record<string, JsonSchema | undefined>;
    // Unique tuples are materialized as real IDB indexes (see `performSetup`)
    // under the same `cols.join("_")` name the planner derives, so they can
    // narrow scans exactly like regular indexes. The base class guarantees no
    // tuple appears in both lists, so the union has no duplicate.
    this.cursorSafeIndexes = [...this.indexes, ...this.uniqueIndexes].filter((columns) =>
      columns.every(
        (column) => required.has(String(column)) && !schemaAdmitsNull(properties[String(column)])
      )
    );
    return this.cursorSafeIndexes;
  }

  /**
   * Picks the best index to narrow a criteria-based scan, preferring indexes
   * whose prefix covers every criteria column (so callers can use the native
   * `count()` API) and falling back to the longest equality-prefix match.
   *
   * Upper bound uses `[]` as a sentinel that compares greater than any
   * primitive value at the next index position (per IndexedDB key ordering:
   * array > binary > string > date > number). Assumes subsequent indexed
   * columns hold primitive values — array-valued columns would compare
   * greater than `[]` and slip outside the range.
   */
  private createIndexedRange(
    store: IDBObjectStore,
    criteria: SearchCriteria<Entity>
  ):
    | {
        source: IDBObjectStore | IDBIndex;
        range: IDBKeyRange | undefined;
        coversCriteria: boolean;
      }
    | undefined {
    const criteriaColumns = Object.keys(criteria) as Array<keyof Entity>;
    if (criteriaColumns.length === 0) return undefined;

    let best:
      | {
          indexName: string;
          prefixValues: unknown[];
          fullMatch: boolean;
          coversCriteria: boolean;
        }
      | undefined;

    for (const indexColumns of this.getCursorSafeIndexes()) {
      const prefixValues: unknown[] = [];
      for (const column of indexColumns) {
        const value = this.getEqualityCriterionValue(criteria, column);
        if (value === undefined) break;
        prefixValues.push(value);
      }

      if (prefixValues.length === 0) continue;

      const indexedPrefix = indexColumns.slice(0, prefixValues.length);
      const coversCriteria = criteriaColumns.every((column) => indexedPrefix.includes(column));

      const better =
        !best ||
        (coversCriteria && !best.coversCriteria) ||
        (coversCriteria === best.coversCriteria && prefixValues.length > best.prefixValues.length);

      if (better) {
        best = {
          indexName: indexColumns.map((column) => String(column)).join("_"),
          prefixValues,
          fullMatch: prefixValues.length === indexColumns.length,
          coversCriteria,
        };
      }
    }

    if (!best) return undefined;

    const range = best.fullMatch
      ? IDBKeyRange.only(best.prefixValues.length === 1 ? best.prefixValues[0] : best.prefixValues)
      : IDBKeyRange.bound(best.prefixValues, [...best.prefixValues, []]);

    return {
      source: store.index(best.indexName),
      range,
      coversCriteria: best.coversCriteria,
    };
  }

  /**
   * Counts rows matching the specified search criteria.
   *
   * Uses the native `count()` API when an index prefix covers every criteria
   * column. Otherwise narrows via the longest matching index prefix and
   * filters the remaining columns during cursor iteration. Falls back to a
   * full store scan only when no index applies.
   */
  override async count(criteria?: SearchCriteria<Entity>): Promise<number> {
    if (!criteria || Object.keys(criteria).length === 0) {
      return await this.size();
    }

    this.validateQueryParams(criteria);
    const db = await this.getDb();

    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readonly");
      const store = transaction.objectStore(this.table);
      const plan = this.createIndexedRange(store, criteria);

      if (plan?.coversCriteria) {
        const request = plan.source.count(plan.range);
        request.onerror = () => reject(request.error);
        request.onsuccess = () => resolve(request.result);
        return;
      }

      const source = plan?.source ?? store;
      const range = plan?.range;
      let count = 0;
      const request = source.openCursor(range);
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        const cursor = request.result;
        if (!cursor) {
          resolve(count);
          return;
        }
        if (this.matchesCriteria(cursor.value as Entity, criteria)) {
          count += 1;
        }
        cursor.continue();
      };
    });
  }

  async getOffsetPage(offset: number, limit: number): Promise<Entity[] | undefined> {
    if (offset < 0) {
      throw new RangeError(`offset must be non-negative, got ${offset}`);
    }
    if (limit <= 0) {
      return undefined;
    }

    const db = await this.getDb();
    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readonly");
      const store = transaction.objectStore(this.table);
      const request = store.openCursor();
      const entities: Entity[] = [];
      let skipped = false;

      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        const cursor = request.result;
        if (cursor) {
          if (!skipped && offset > 0) {
            skipped = true;
            cursor.advance(offset);
            return;
          }

          entities.push(cursor.value);
          if (entities.length === limit) {
            resolve(entities);
            return;
          }
          cursor.continue();
        } else {
          resolve(entities.length > 0 ? entities : undefined);
        }
      };
    });
  }

  private matchesCriteria(record: Entity, criteria: DeleteSearchCriteria<Entity>): boolean {
    for (const column of Object.keys(criteria) as Array<keyof Entity>) {
      const criterion = criteria[column];
      const recordValue = record[column];

      const normalized = normalizeCriterion<Entity[keyof Entity]>(criterion);
      if (normalized.kind === "in") {
        // Strict membership, matching the `=` arm: no coercion.
        if (!matchesInCriterion(recordValue, normalized.values)) return false;
        continue;
      }
      if (normalized.kind === "not-in") {
        // Carries its own null rules (a null column is excluded, a null in the
        // list excludes everything), so it must precede the blanket null check
        // below rather than being folded into it.
        if (!matchesNotInCriterion(recordValue, normalized.values)) return false;
        continue;
      }
      if (normalized.kind === "like") {
        if (!matchesLikeCriterion(recordValue, normalized.pattern)) return false;
        continue;
      }
      const { operator, value } = normalized;

      // `=` and `!=` carry their own null semantics (see the matches* helpers);
      // every ordering operator is UNKNOWN against null, so the row is excluded.
      if (
        operator !== "=" &&
        operator !== "!=" &&
        (recordValue === null || recordValue === undefined)
      ) {
        return false;
      }

      switch (operator) {
        case "=":
          // Shared rule: a null criterion matches null OR an absent column.
          if (!matchesEqualityCriterion(recordValue, value)) return false;
          break;
        case "!=":
          if (!matchesInequalityCriterion(recordValue, value)) return false;
          break;
        case "<":
          if (!(recordValue < value)) return false;
          break;
        case "<=":
          if (!(recordValue <= value)) return false;
          break;
        case ">":
          if (!(recordValue > value)) return false;
          break;
        case ">=":
          if (!(recordValue >= value)) return false;
          break;
        default:
          return false;
      }
    }
    return true;
  }

  async deleteSearch(criteria: DeleteSearchCriteria<Entity>): Promise<void> {
    if (!this.shouldRunDeleteSearch(criteria)) return;

    const db = await this.getDb();

    return new Promise((resolve, reject) => {
      try {
        const transaction = db.transaction(this.table, "readwrite");
        const store = transaction.objectStore(this.table);

        transaction.oncomplete = () => {
          safeEmit(this.events, "delete", this.deleteIdentity(criteria));
          this.hybridManager?.notifyLocalChange();
          resolve();
        };

        transaction.onerror = () => {
          reject(transaction.error);
        };

        const getAllRequest = store.getAll();

        getAllRequest.onsuccess = () => {
          const allRecords: Entity[] = getAllRequest.result;

          const recordsToDelete = allRecords.filter((record) =>
            this.matchesCriteria(record, criteria)
          );

          if (recordsToDelete.length === 0) {
            return;
          }

          for (const record of recordsToDelete) {
            const primaryKey = this.primaryKeyColumns().reduce((key, col) => {
              // @ts-expect-error - We know these properties exist on the record
              key[col] = record[col];
              return key;
            }, {} as PrimaryKey);

            const request = store.delete(this.getIndexedKey(primaryKey));

            request.onerror = () => {
              console.error("Error deleting record:", request.error);
            };
          }
        };

        getAllRequest.onerror = () => {
          reject(getAllRequest.error);
        };
      } catch (error) {
        reject(error);
      }
    });
  }

  /**
   * Compare-and-swap `updateWhere`: opens a single `readwrite` transaction
   * on the object store, walks the first cursor row satisfying `match`,
   * applies `patch` in place via `cursor.update()`, and resolves on
   * `tx.oncomplete`. Two concurrent callers with overlapping `match`
   * criteria therefore serialize on the underlying IDB transaction rather
   * than racing between a `query()` and a `put()`. Uniqueness is enforced
   * by IDB's native UNIQUE indexes — a patch that collides with another
   * row rejects the cursor request with `ConstraintError`, which aborts
   * the transaction (mirroring how {@link put} propagates the same error).
   *
   * The cursor source is picked with the same equality-prefix planner
   * {@link createIndexedRange} uses for {@link count}: an index scan when
   * an equality prefix narrows the criteria, otherwise a full store scan.
   */
  async updateWhere(
    match: SearchCriteria<Entity>,
    patch: Partial<Entity>
  ): Promise<Entity | undefined> {
    this.assertPatchKeepsPrimaryKey(patch);
    this.validateQueryParams(match);
    const db = await this.getDb();

    return new Promise<Entity | undefined>((resolve, reject) => {
      let tx: IDBTransaction;
      try {
        tx = db.transaction(this.table, "readwrite");
      } catch (err) {
        reject(err);
        return;
      }
      const store = tx.objectStore(this.table);
      const plan = this.createIndexedRange(store, match);
      const source = plan?.source ?? store;
      const range = plan?.range;

      let updated: Entity | undefined;

      tx.oncomplete = () => {
        if (updated !== undefined) {
          safeEmit(this.events, "put", updated);
          this.hybridManager?.notifyLocalChange();
        }
        resolve(updated);
      };
      tx.onerror = () => reject(tx.error);
      tx.onabort = () => reject(tx.error ?? new Error("updateWhere transaction aborted"));

      const request = source.openCursor(range);
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        const cursor = request.result;
        if (!cursor) return;

        const record = cursor.value as Entity;
        if (!this.matchesCriteria(record, match)) {
          cursor.continue();
          return;
        }

        const candidate = { ...record, ...patch } as Entity;
        const updateRequest = cursor.update(candidate);
        updateRequest.onsuccess = () => {
          updated = candidate;
        };
        updateRequest.onerror = () => {
          // Let the ConstraintError (unique-index collision) abort the
          // transaction; tx.onabort surfaces it to the caller.
        };
      };
    });
  }

  private getEqualityCriterionValue(
    criteria: SearchCriteria<Entity>,
    column: keyof Entity
  ): Entity[keyof Entity] | undefined {
    const criterion = criteria[column];
    if (criterion === undefined) return undefined;
    // A list or pattern criterion is not a single key, so it can't drive an
    // IDB index lookup; returning undefined sends it to the in-cursor filter
    // instead. Every such guard must be tested: none passes `isSearchCondition`,
    // so an unguarded `not-in` or `like` would fall through to the literal-value
    // return at the bottom and be used as an equality key — matching nothing.
    if (
      isSearchInCondition(criterion) ||
      isSearchNotInCondition(criterion) ||
      isSearchLikeCondition(criterion)
    ) {
      return undefined;
    }
    if (isSearchCondition(criterion)) {
      if (criterion.operator !== "=") return undefined;
      // `null` is not a valid IDB key, so `IDBKeyRange.only`/`bound` would throw
      // a DataError on it. No range could serve the criterion anyway: IDB omits
      // a record from an index entirely when its indexed value is null, so the
      // rows being asked for are not in the index to be scanned. Report the
      // criterion as unusable for narrowing and let `matchesEqualityCriterion`
      // in the cursor filter decide it.
      if (criterion.value === null) return undefined;
      return criterion.value as Entity[keyof Entity];
    }
    if (criterion === null) return undefined;
    return criterion as Entity[keyof Entity];
  }

  private compareByOrder(a: Entity, b: Entity, options?: QueryOptions<Entity>): number {
    if (!options?.orderBy) return 0;
    for (const { column, direction } of options.orderBy) {
      const aVal = a[column] as string | number | null | undefined;
      const bVal = b[column] as string | number | null | undefined;
      if (aVal == null && bVal == null) continue;
      if (aVal == null) return direction === "ASC" ? -1 : 1;
      if (bVal == null) return direction === "ASC" ? 1 : -1;
      if (aVal < bVal) return direction === "ASC" ? -1 : 1;
      if (aVal > bVal) return direction === "ASC" ? 1 : -1;
    }
    return 0;
  }

  private createIndexedQuery(
    store: IDBObjectStore,
    criteria: SearchCriteria<Entity>,
    options?: QueryOptions<Entity>
  ): {
    source: IDBObjectStore | IDBIndex;
    range: IDBKeyRange | undefined;
    direction: IDBCursorDirection;
    satisfiesOrder: boolean;
    appliedLimit: boolean;
    appliedOffset: boolean;
    skipRemaining: number;
  } {
    const orderBy = options?.orderBy ?? [];
    let best:
      | {
          indexName: string;
          prefixValues: unknown[];
          fullMatch: boolean;
          satisfiesOrder: boolean;
          direction: IDBCursorDirection;
        }
      | undefined;

    for (const indexColumns of this.getCursorSafeIndexes()) {
      const prefixValues: unknown[] = [];
      for (const column of indexColumns) {
        const value = this.getEqualityCriterionValue(criteria, column);
        if (value === undefined) break;
        prefixValues.push(value);
      }

      if (prefixValues.length === 0) continue;

      const remainingColumns = indexColumns.slice(prefixValues.length);
      let redundantOrderPrefixLength = 0;
      while (
        redundantOrderPrefixLength < orderBy.length &&
        redundantOrderPrefixLength < prefixValues.length &&
        orderBy[redundantOrderPrefixLength]?.column === indexColumns[redundantOrderPrefixLength]
      ) {
        redundantOrderPrefixLength++;
      }
      const normalizedOrderBy = orderBy.slice(redundantOrderPrefixLength);
      const satisfiesOrder =
        normalizedOrderBy.length === 0 ||
        (normalizedOrderBy.length <= remainingColumns.length &&
          normalizedOrderBy.every((order, index) => order.column === remainingColumns[index]) &&
          orderBy.every((order) => order.direction === orderBy[0]?.direction));

      if (!satisfiesOrder && best) continue;

      if (
        !best ||
        (satisfiesOrder && !best.satisfiesOrder) ||
        prefixValues.length > best.prefixValues.length
      ) {
        best = {
          indexName: indexColumns.map((column) => String(column)).join("_"),
          prefixValues,
          fullMatch: prefixValues.length === indexColumns.length,
          satisfiesOrder,
          direction: orderBy[0]?.direction === "DESC" ? "prev" : "next",
        };
      }
    }

    const appliedLimit = Boolean(best?.satisfiesOrder && options?.limit !== undefined);
    const appliedOffset = Boolean(best?.satisfiesOrder && options?.offset !== undefined);

    if (!best) {
      return {
        source: store,
        range: undefined,
        direction: orderBy[0]?.direction === "DESC" ? "prev" : "next",
        satisfiesOrder: false,
        appliedLimit: false,
        appliedOffset: false,
        skipRemaining: 0,
      };
    }

    const source = store.index(best.indexName);
    // See createIndexedRange for the `[]` upper-bound sentinel rationale.
    const keyRange = best.fullMatch
      ? IDBKeyRange.only(best.prefixValues.length === 1 ? best.prefixValues[0] : best.prefixValues)
      : IDBKeyRange.bound(best.prefixValues, [...best.prefixValues, []]);

    return {
      source,
      range: keyRange,
      direction: best.direction,
      satisfiesOrder: best.satisfiesOrder,
      appliedLimit,
      appliedOffset,
      skipRemaining: appliedOffset ? (options?.offset ?? 0) : 0,
    };
  }

  async query(
    criteria: SearchCriteria<Entity>,
    options?: QueryOptions<Entity>
  ): Promise<Entity[] | undefined> {
    this.validateQueryParams(criteria, options);
    const db = await this.getDb();

    return new Promise((resolve, reject) => {
      const transaction = db.transaction(this.table, "readonly");
      const store = transaction.objectStore(this.table);
      const indexedQuery = this.createIndexedQuery(store, criteria, options);
      const results: Entity[] = [];
      const request = indexedQuery.source.openCursor(indexedQuery.range, indexedQuery.direction);

      request.onsuccess = () => {
        const cursor = request.result;
        if (!cursor) {
          let finalResults = results;

          if (!indexedQuery.satisfiesOrder && options?.orderBy && options.orderBy.length > 0) {
            finalResults = [...finalResults].sort((a, b) => this.compareByOrder(a, b, options));
          }

          if (!indexedQuery.appliedOffset && options?.offset !== undefined) {
            finalResults = finalResults.slice(options.offset);
          }

          if (!indexedQuery.appliedLimit && options?.limit !== undefined) {
            finalResults = finalResults.slice(0, options.limit);
          }

          const result = finalResults.length > 0 ? finalResults : undefined;
          safeEmit(this.events, "query", criteria as Partial<Entity>, result);
          resolve(result);
          return;
        }

        const record = cursor.value as Entity;
        if (this.matchesCriteria(record, criteria)) {
          if (indexedQuery.skipRemaining > 0) {
            indexedQuery.skipRemaining -= 1;
          } else {
            results.push(record);
            if (indexedQuery.appliedLimit && results.length === options?.limit) {
              const result = results.length > 0 ? results : undefined;
              safeEmit(this.events, "query", criteria as Partial<Entity>, result);
              resolve(result);
              return;
            }
          }
        }

        cursor.continue();
      };

      request.onerror = () => reject(request.error);
    });
  }

  /**
   * Strict, projected query served entirely by a covering compound index.
   * Uses `openKeyCursor` — never reads `cursor.value` — so only the index key
   * bytes are loaded into memory. Ideal for tables with large value blobs.
   *
   * Throws {@link CoveringIndexMissingError} when no registered index can serve
   * the request (i.e. the index does not cover all select + orderBy columns).
   *
   * A criterion on a column of the chosen index that must match null-valued
   * rows is rejected with {@link StorageUnsupportedError} — a `null` equality,
   * or an empty `not-in` list, which excludes nothing and so matches every row.
   * IndexedDB omits a record from an index when its indexed value is null, so
   * those rows exist in no index and a projection reading values out of
   * `cursor.key` can never produce them — the request would return
   * silently-short results rather than the matching rows. Use {@link query},
   * which reads whole records and filters them in the cursor.
   */
  override async queryIndex<K extends keyof Entity & string>(
    criteria: SearchCriteria<Entity>,
    options: CoveringIndexQueryOptions<Entity, K>
  ): Promise<Pick<Entity, K>[]> {
    this.validateSelect(options);
    this.validateQueryParams(criteria, options);

    const registered = this.indexes.map((cols) => {
      const cs = Array.isArray(cols) ? (cols as string[]) : [cols as string];
      return { name: cs.join("_"), keyPath: cs };
    });

    const picked = pickCoveringIndex({
      table: this.table,
      indexes: registered,
      criteriaColumns: Object.keys(criteria),
      orderByColumns: (options.orderBy ?? []).map((o) => ({
        column: String(o.column),
        direction: o.direction,
      })),
      selectColumns: options.select.map(String),
      primaryKeyColumns: this.primaryKeyColumns().map(String),
    });

    for (const col of picked.keyPath) {
      const criterion = (criteria as Record<string, unknown>)[col];
      // An empty exclusion list matches every row, nulls included — the only
      // criterion besides a null equality that a null-valued column can
      // satisfy. Rejected for the same reason: those records are in no index,
      // so an index scan returns a silently short result instead of them.
      if (isSearchNotInCondition(criterion) && criterion.value.length === 0) {
        throw new StorageUnsupportedError(
          `An empty "not-in" criterion on indexed column "${col}" (it matches every ` +
            `row including null-valued ones, but IndexedDB omits those from an index, ` +
            `so an index scan can never reach them — use query() instead)`,
          "IndexedDbTabularStorage"
        );
      }
      const isNullEquality = isSearchCondition(criterion)
        ? criterion.operator === "=" && criterion.value === null
        : criterion === null;
      if (isNullEquality) {
        throw new StorageUnsupportedError(
          `A null equality criterion on indexed column "${col}" (IndexedDB omits ` +
            `null-valued records from an index, so an index scan can never reach ` +
            `them — use query() instead)`,
          "IndexedDbTabularStorage"
        );
      }
    }

    const db = await this.getDb();
    return new Promise((resolve, reject) => {
      const tx = db.transaction(this.table, "readonly");
      const store = tx.objectStore(this.table);
      const idx = store.index(picked.name);

      // Only push columns whose criterion is a direct equality. A non-equality
      // operator breaks the prefix; the in-cursor compareWithOperator filter
      // below handles those columns.
      const prefix: unknown[] = [];
      for (const col of picked.keyPath) {
        const c = (criteria as Record<string, unknown>)[col];
        if (c === undefined && !(col in (criteria as Record<string, unknown>))) break;
        // A list criterion matches several keys (or excludes some), so it
        // cannot extend a single equality prefix — stop here and let the
        // in-cursor filter handle it. Same reason both guards are needed here
        // as in `getEqualityCriterionValue`: a `not-in` that reached the
        // `else` below would be pushed onto the prefix as a raw key.
        if (isSearchInCondition(c) || isSearchNotInCondition(c) || isSearchLikeCondition(c)) break;
        if (isSearchCondition(c)) {
          if (c.operator !== "=") break;
          // Defense in depth: the guard above already rejected a null equality
          // on a key-path column, and `null` is not a valid IDB key.
          if (c.value === null) break;
          prefix.push(c.value);
        } else {
          // `undefined` breaks alongside `null`: it matches no row at all, and
          // pushing it would hand `IDBKeyRange` a value that is not a valid
          // key. Stopping here lets the in-cursor filter return the empty
          // answer the SQL backends give.
          if (c === null || c === undefined) break;
          prefix.push(c);
        }
      }
      // `[...prefix, []]` is greater than any key starting with prefix in IDB's
      // comparison ordering — used as the upper bound for prefix scans.
      const range =
        prefix.length === 0
          ? undefined
          : prefix.length === picked.keyPath.length
            ? IDBKeyRange.only(prefix.length === 1 ? prefix[0] : prefix)
            : IDBKeyRange.bound(prefix, [...prefix, []]);

      const direction: IDBCursorDirection = picked.reverseDirection ? "prev" : "next";
      // openKeyCursor — never reads cursor.value, only the index key and primaryKey
      const request = idx.openKeyCursor(range, direction);
      const out: Pick<Entity, K>[] = [];
      let toSkip = options.offset ?? 0;

      const keyPathPositions = new Map<string, number>();
      picked.keyPath.forEach((col, i) => keyPathPositions.set(col, i));

      const pkCols = this.primaryKeyColumns().map(String);
      const pkPositions = new Map<string, number>();
      pkCols.forEach((col, i) => pkPositions.set(col, i));

      request.onsuccess = () => {
        const cursor = request.result;
        if (!cursor) {
          resolve(out);
          return;
        }

        const key = cursor.key;

        const row = {} as Record<string, unknown>;
        for (const col of options.select) {
          const colStr = String(col);
          const pos = keyPathPositions.get(colStr);
          if (pos !== undefined) {
            row[colStr] = Array.isArray(key) ? key[pos] : key;
          } else {
            // Column must be a primary key column — use cursor.primaryKey
            if (pkCols.length === 1 && colStr === pkCols[0]) {
              row[colStr] = cursor.primaryKey;
            } else {
              const pkPos = pkPositions.get(colStr);
              if (pkPos !== undefined) {
                row[colStr] = Array.isArray(cursor.primaryKey)
                  ? (cursor.primaryKey as unknown[])[pkPos]
                  : cursor.primaryKey;
              }
            }
          }
        }

        // Apply criteria for index positions beyond the equality prefix.
        // Positions [0, prefix.length) are guaranteed-equal by the IDBKeyRange,
        // so they don't need re-checking. Positions >= prefix.length must be
        // filtered here — this includes plain-value equalities trailing a
        // non-equality break (criteria like `{a:1, b:>=5, c:3}` with prefix=[1]
        // need an in-cursor `c === 3` check) and any SearchCondition.
        let matches = true;
        for (const [col, crit] of Object.entries(criteria as Record<string, unknown>)) {
          const pos = keyPathPositions.get(col);
          if (pos === undefined) continue;
          if (pos < prefix.length) continue; // covered by IDBKeyRange
          const valFromKey = Array.isArray(key) ? (key as unknown[])[pos] : key;
          const normalized = normalizeCriterion<unknown>(crit);
          const ok =
            normalized.kind === "in"
              ? matchesInCriterion(valFromKey, normalized.values)
              : normalized.kind === "not-in"
                ? matchesNotInCriterion(valFromKey, normalized.values)
                : normalized.kind === "like"
                  ? matchesLikeCriterion(valFromKey, normalized.pattern)
                  : compareWithOperator(valFromKey, normalized.operator, normalized.value);
          if (!ok) {
            matches = false;
            break;
          }
        }

        if (matches) {
          if (toSkip > 0) {
            toSkip -= 1;
          } else {
            out.push(row as Pick<Entity, K>);
            if (options.limit !== undefined && out.length >= options.limit) {
              resolve(out);
              return;
            }
          }
        }

        cursor.continue();
      };

      request.onerror = () => reject(request.error);
    });
  }

  private getHybridManager(): HybridSubscriptionManager<
    Entity,
    string,
    TabularChangePayload<Entity>
  > {
    if (!this.hybridManager) {
      const channelName = `indexeddb-tabular-${this.table}`;

      this.hybridManager = new HybridSubscriptionManager<
        Entity,
        string,
        TabularChangePayload<Entity>
      >(
        channelName,
        async () => {
          const entities = (await this.getAll()) || [];
          const map = new Map<string, Entity>();
          for (const entity of entities) {
            const { key } = this.separateKeyValueFromCombined(entity);
            const fingerprint = await makeFingerprint(key);
            map.set(fingerprint, entity);
          }
          return map;
        },
        compareEntitiesForChange,
        {
          insert: (item) => ({ type: "INSERT" as const, new: item }),
          update: (oldItem, newItem) => ({ type: "UPDATE" as const, old: oldItem, new: newItem }),
          delete: (item) => ({ type: "DELETE" as const, old: item }),
        },
        {
          defaultIntervalMs: 1000,
          useBroadcastChannel: this.hybridOptions.useBroadcastChannel,
          backupPollingIntervalMs: this.hybridOptions.backupPollingIntervalMs,
        }
      );
    }
    return this.hybridManager;
  }

  /**
   * Uses polling since IndexedDB has no native cross-tab change notifications.
   */
  public override subscribeToChanges(
    callback: (change: TabularChangePayload<Entity>) => void,
    options?: TabularSubscribeOptions
  ): () => void {
    // Kept synchronous; the hybrid manager's getAll() invokes setupDatabase()
    // when needed.
    const intervalMs = options?.pollingIntervalMs ?? 1000;
    const manager = this.getHybridManager();
    return manager.subscribe(callback, { intervalMs });
  }

  public override destroy(): void {
    if (this.hybridManager) {
      this.hybridManager.destroy();
      this.hybridManager = null;
    }
    this.db?.close();
  }
}

/**
 * Whether a column's schema admits `null`, in any of the spellings JSON Schema
 * offers for it. Mirrors the nullability test the SQL backends use to decide
 * between `NULL` and `NOT NULL`.
 */
function schemaAdmitsNull(typeDef: JsonSchema | undefined): boolean {
  if (typeDef === undefined) return false;
  if (typeof typeDef === "boolean") return typeDef;
  if (typeDef.type === "null") return true;
  if (Array.isArray(typeDef.type)) return typeDef.type.includes("null");
  const branches = typeDef.anyOf ?? typeDef.oneOf;
  if (Array.isArray(branches)) {
    return branches.some((branch) => typeof branch !== "boolean" && branch.type === "null");
  }
  return false;
}

/**
 * Compare two values using a SearchOperator. Used by queryIndex to evaluate
 * non-equality criteria that cannot be expressed as an IDBKeyRange prefix.
 */
function compareWithOperator(a: unknown, op: SearchOperator, b: unknown): boolean {
  const av = a as string | number | null | undefined;
  const bv = b as string | number;
  switch (op) {
    case "=":
      // Same rule `matchesCriteria` applies, so the two agree on every input.
      return matchesEqualityCriterion(av, bv);
    case "!=":
      return matchesInequalityCriterion(av, bv);
    case "<":
      return av !== null && av !== undefined && av < bv;
    case "<=":
      return av !== null && av !== undefined && av <= bv;
    case ">":
      return av !== null && av !== undefined && av > bv;
    case ">=":
      return av !== null && av !== undefined && av >= bv;
  }
}
