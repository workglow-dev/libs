describe("SqliteTabularStorage shared-connection safety", () => {
  async function makeSharedPair(): Promise<
    readonly [
      SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>,
      SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>,
      Sqlite.Database,
    ]
  > {
    const db = new Sqlite.Database(":memory:");
    const tableA = `shared_a_${uuid4().replace(/-/g, "_")}`;
    const tableB = `shared_b_${uuid4().replace(/-/g, "_")}`;
    const a = new SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      db,
      tableA,
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    const b = new SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      db,
      tableB,
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await a.setupDatabase();
    await b.setupDatabase();
    return [a, b, db] as const;
  }

  it("unrelated concurrent sibling op waits for the transaction instead of being refused", async () => {
    const [a, b] = await makeSharedPair();
    let releaseInner: () => void = () => {};
    const innerCanFinish = new Promise<void>((resolve) => {
      releaseInner = resolve;
    });
    let signalTxStarted: () => void = () => {};
    const txStarted = new Promise<void>((resolve) => {
      signalTxStarted = resolve;
    });

    const order: string[] = [];
    const txPromise = a.withTransaction(async (tx) => {
      // After this awaited put returns, we are provably inside the tx body,
      // which means the shared ConnectionMutex has already set
      // `state.txOwners = {a}`.
      await tx.put({ name: "tx-row", type: "x", option: "tx", success: true });
      signalTxStarted();
      await innerCanFinish;
      order.push("TX-BODY-END");
    });

    await txStarted;

    // A sibling put from a *different* storage instance on the same handle,
    // issued from a task that is NOT an async descendant of the transaction
    // body. Its write cannot escape the BEGIN, so refusing it would only
    // dead-letter a caller that did nothing wrong — in its own task, where the
    // transaction's caller cannot catch it. It queues on the connection chain.
    let siblingErr: unknown;
    const sibling = b
      .put({ name: "sibling-row", type: "x", option: "sib", success: true })
      .then(() => {
        order.push("SIBLING-WRITE");
      })
      .catch((err: unknown) => {
        siblingErr = err;
      });

    // An unrelated concurrent READ on the same connection, also queued rather
    // than run: it would otherwise execute on the same session inside the open
    // BEGIN and report whatever the transaction has written so far.
    let readSettled = false;
    const concurrentRead = b.get({ name: "sibling-row", type: "x" }).then((row) => {
      readSettled = true;
      return row;
    });

    await new Promise((resolve) => setTimeout(resolve, 20));
    // Neither refused nor slipped inside the open BEGIN. The sibling write has
    // not landed, and the sibling read has not answered.
    expect(siblingErr).toBeUndefined();
    expect(order).toEqual([]);
    expect(readSettled).toBe(false);

    releaseInner();
    await txPromise;
    await sibling;
    // The read ran after COMMIT released the connection, so it sees the
    // sibling write that was queued ahead of it.
    expect(await concurrentRead).toBeDefined();

    expect(siblingErr).toBeUndefined();
    expect(order).toEqual(["TX-BODY-END", "SIBLING-WRITE"]);
    expect(await b.get({ name: "sibling-row", type: "x" })).toBeDefined();

    // The outer tx still commits cleanly, and the shared connection is
    // released so a further sibling put also succeeds.
    expect(await a.get({ name: "tx-row", type: "x" })).toBeDefined();
    await b.put({ name: "post-tx-row", type: "x", option: "sib", success: true });
    expect(await b.get({ name: "post-tx-row", type: "x" })).toBeDefined();
  });

  it("sibling single-op from inside the transaction body still throws ConnectionReentryError", async () => {
    const [a, b] = await makeSharedPair();

    // A descendant of the body is the caller whose write WOULD escape the
    // BEGIN — it must still be refused, and its row must not exist.
    let siblingErr: unknown;
    await a.withTransaction(async (tx) => {
      await tx.put({ name: "tx-row", type: "x", option: "tx", success: true });
      await b
        .put({ name: "sibling-row", type: "x", option: "sib", success: true })
        .catch((err: unknown) => {
          siblingErr = err;
        });
    });

    expect(siblingErr).toBeInstanceOf(ConnectionReentryError);
    const reentry = siblingErr as ConnectionReentryError;
    expect(reentry.mode).toBe("sibling-op");
    expect(reentry.message).toContain("sibling operation");
    expect(reentry.message).toContain("'tx' proxy");
    expect(reentry.message).toContain("SAVEPOINT");
    expect(reentry.message).toContain("single storage instance");

    expect(await b.get({ name: "sibling-row", type: "x" })).toBeUndefined();
    expect(await a.get({ name: "tx-row", type: "x" })).toBeDefined();
  });

  it("rejects cross-instance nested withTransaction within 500ms (no hang)", async () => {
    const [a, b] = await makeSharedPair();
    const start = Date.now();
    let caught: unknown;
    try {
      await a.withTransaction(async () => {
        // From inside a's transaction, another instance (b) tries to open its own
        // withTransaction on the shared handle. This must fail, not deadlock.
        await b.withTransaction(async () => {
          // unreachable
        });
      });
    } catch (err) {
      caught = err;
    }
    expect(caught).toBeInstanceOf(ConnectionReentryError);
    const reentry = caught as ConnectionReentryError;
    expect(reentry.mode).toBe("nested-transaction");
    expect(reentry.message).toContain("open its own transaction");
    expect(reentry.message).toContain("'tx' proxy");
    expect(reentry.message).toContain("SAVEPOINT");
    expect(reentry.message).toContain("single storage instance");
    expect(Date.now() - start).toBeLessThan(500);
  });

  it("same-instance nested writes via tx proxy still work", async () => {
    const [a] = await makeSharedPair();
    await a.withTransaction(async (tx) => {
      await tx.put({ name: "n1", type: "x", option: "v1", success: true });
      await tx.putBulk([
        { name: "n2", type: "x", option: "v2", success: true },
        { name: "n3", type: "x", option: "v3", success: true },
      ]);
    });
    expect(await a.get({ name: "n1", type: "x" })).toBeDefined();
    expect(await a.get({ name: "n2", type: "x" })).toBeDefined();
    expect(await a.get({ name: "n3", type: "x" })).toBeDefined();
  });

  it("withConnectionTransaction commits writes across two tables", async () => {
    const [a, b] = await makeSharedPair();
    await withConnectionTransaction([a, b], async () => {
      await a.put({ name: "from-a", type: "x", option: "va", success: true });
      await b.put({ name: "from-b", type: "x", option: "vb", success: true });
    });
    expect(await a.get({ name: "from-a", type: "x" })).toMatchObject({ option: "va" });
    expect(await b.get({ name: "from-b", type: "x" })).toMatchObject({ option: "vb" });
  });

  it("two concurrent withConnectionTransaction calls with overlapping participant sets both commit", async () => {
    const [a, b, db] = await makeSharedPair();
    const c = new SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      db,
      `shared_c_${uuid4().replace(/-/g, "_")}`,
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await c.setupDatabase();

    // The shape a concurrent sweep produces: one unit of work opens a
    // transaction over {a, b} and another, in a different task on the same
    // handle, opens one over {b, c}. The sets overlap but are not equal, and
    // neither call is an async descendant of the other. Only one BEGIN can be
    // open on a single SQLite handle, so the second waits — refusing it would
    // fail a unit of work that has nothing wrong with it.
    const order: string[] = [];
    let releaseFirst: () => void = () => {};
    const firstCanFinish = new Promise<void>((resolve) => {
      releaseFirst = resolve;
    });
    let signalFirstStarted: () => void = () => {};
    const firstStarted = new Promise<void>((resolve) => {
      signalFirstStarted = resolve;
    });

    const first = withConnectionTransaction([a, b], async () => {
      order.push("BEGIN-1");
      await a.put({ name: "first", type: "x", option: "va", success: true });
      signalFirstStarted();
      await firstCanFinish;
      order.push("END-1");
    });
    await firstStarted;

    let secondError: unknown;
    const second = withConnectionTransaction([b, c], async () => {
      order.push("BEGIN-2");
      await c.put({ name: "second", type: "x", option: "vc", success: true });
    }).catch((err: unknown) => {
      secondError = err;
    });

    await new Promise((resolve) => setTimeout(resolve, 20));
    expect(secondError).toBeUndefined();
    expect(order).toEqual(["BEGIN-1"]);

    releaseFirst();
    await first;
    await second;

    expect(secondError).toBeUndefined();
    expect(order).toEqual(["BEGIN-1", "END-1", "BEGIN-2"]);
    expect(await a.get({ name: "first", type: "x" })).toMatchObject({ option: "va" });
    expect(await c.get({ name: "second", type: "x" })).toMatchObject({ option: "vc" });
  });

  it("withConnectionTransaction rolls back both tables when the callback throws", async () => {
    const [a, b] = await makeSharedPair();
    await a.put({ name: "kept", type: "x", option: "base", success: true });

    await expect(
      withConnectionTransaction([a, b], async () => {
        await a.put({ name: "from-a", type: "x", option: "va", success: true });
        await b.put({ name: "from-b", type: "x", option: "vb", success: true });
        throw new Error("forced rollback");
      })
    ).rejects.toThrow("forced rollback");

    expect(await a.get({ name: "kept", type: "x" })).toBeDefined();
    expect(await a.get({ name: "from-a", type: "x" })).toBeUndefined();
    expect(await b.get({ name: "from-b", type: "x" })).toBeUndefined();
  });

  it("withConnectionTransaction still throws sibling-op for a non-enlisted storage", async () => {
    const [a, b, db] = await makeSharedPair();
    const c = new SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      db,
      `shared_c_${uuid4().replace(/-/g, "_")}`,
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await c.setupDatabase();

    let error: unknown;
    await withConnectionTransaction([a, b], async () => {
      await a.put({ name: "enlisted", type: "x", option: "ok", success: true });
      try {
        await c.put({ name: "outsider", type: "x", option: "no", success: true });
      } catch (err) {
        error = err;
      }
    });

    expect(error).toBeInstanceOf(ConnectionReentryError);
    expect((error as ConnectionReentryError).mode).toBe("sibling-op");
    expect(await c.get({ name: "outsider", type: "x" })).toBeUndefined();
    expect(await a.get({ name: "enlisted", type: "x" })).toBeDefined();
  });

  it("withConnectionTransaction rejects participants on different connections", async () => {
    const [a] = await makeSharedPair();
    const [other] = await makeSharedPair();
    await expect(withConnectionTransaction([a, other], async () => undefined)).rejects.toThrow(
      /do not share a connection handle/
    );
  });

  it("withConnectionTransaction refuses to nest on the same connection", async () => {
    const [a, b] = await makeSharedPair();

    let nested: unknown;
    await withConnectionTransaction([a, b], async () => {
      await a.put({ name: "outer", type: "x", option: "outer", success: true });
      try {
        await withConnectionTransaction([a, b], async () => {
          await b.put({ name: "inner", type: "x", option: "inner", success: true });
        });
      } catch (err) {
        nested = err;
      }
    });

    expect(nested).toBeInstanceOf(NestedConnectionTransactionError);
    expect((nested as Error).message).toContain("SAVEPOINT");
    // The inner call must fail BEFORE issuing its own BEGIN, so the outer
    // transaction is untouched and still commits its own work.
    expect(await a.get({ name: "outer", type: "x" })).toMatchObject({ option: "outer" });
    expect(await b.get({ name: "inner", type: "x" })).toBeUndefined();
  });

  it("a rejected nested transaction leaves the outer transaction able to write", async () => {
    const [a, b] = await makeSharedPair();

    await withConnectionTransaction([a, b], async () => {
      await expect(withConnectionTransaction([a, b], async () => undefined)).rejects.toBeInstanceOf(
        NestedConnectionTransactionError
      );
      // A write AFTER the rejected nesting attempt must still join the outer
      // BEGIN — the failed inner call must not have cleared `inTransaction`.
      await a.put({ name: "after-nested", type: "x", option: "va", success: true });
      await b.put({ name: "after-nested", type: "x", option: "vb", success: true });
      throw new Error("forced rollback");
    }).catch((err: unknown) => {
      expect((err as Error).message).toBe("forced rollback");
    });

    expect(await a.get({ name: "after-nested", type: "x" })).toBeUndefined();
    expect(await b.get({ name: "after-nested", type: "x" })).toBeUndefined();
  });

  it("withConnectionTransaction on a DIFFERENT database may nest", async () => {
    const [a, b] = await makeSharedPair();
    const [c, d] = await makeSharedPair();

    await withConnectionTransaction([a, b], async () => {
      await a.put({ name: "outer", type: "x", option: "outer", success: true });
      await withConnectionTransaction([c, d], async () => {
        await c.put({ name: "inner", type: "x", option: "inner", success: true });
      });
    });

    expect(await a.get({ name: "outer", type: "x" })).toMatchObject({ option: "outer" });
    expect(await c.get({ name: "inner", type: "x" })).toMatchObject({ option: "inner" });
  });

  it("a deferred put listener that writes commits, and its own put event fires", async () => {
    const [a, b] = await makeSharedPair();

    const seen: string[] = [];
    let writing = false;
    b.on("put", (entity: { name: string }) => {
      seen.push(entity.name);
      if (writing) return;
      writing = true;
      // A listener reacting to the flushed commit event by writing back
      // through the same storage: the write must take its own transaction and
      // its own `put` event must reach this listener rather than being queued
      // onto a buffer nothing drains.
      void b.put({ name: "marker", type: "x", option: "from-listener", success: true });
    });

    await withConnectionTransaction([a, b], async () => {
      await b.put({ name: "in-tx", type: "x", option: "vb", success: true });
    });

    await vi.waitFor(() => expect(seen).toContain("marker"));
    expect(seen[0]).toBe("in-tx");
    expect(await b.get({ name: "marker", type: "x" })).toMatchObject({
      option: "from-listener",
    });
  });
});

describe("SqliteTabularStorage entity prototypes", () => {
  const row = {
    id: "p1",
    category: "a",
    subcategory: "x",
    value: 1,
    createdAt: "2025-01-01T00:00:00Z",
    updatedAt: "2025-01-01T00:00:00Z",
  };

  // Each storage opens its own `:memory:` database, so one fixed table name
  // cannot collide with another test's.
  async function makeStorage(): Promise<
    SqliteTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>
  > {
    const storage = new SqliteTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      ":memory:",
      "proto_probe",
      SearchSchema,
      SearchPrimaryKeyNames
    );
    await storage.setupDatabase();
    return storage;
  }

  it("returns get() entities as plain objects", async () => {
    const storage = await makeStorage();
    try {
      await storage.put(row);
      const got = await storage.get({ id: "p1" });
      // The driver hands back null-prototype rows; anything that reaches a caller
      // has to look like the plain objects every other backend returns.
      expect(Object.getPrototypeOf(got)).toBe(Object.prototype);
      // Every nullable column SearchSchema declares comes back as an explicit
      // null, `tag` included -- a column added to the schema has to be listed
      // here or toStrictEqual fails on the extra key.
      expect(got).toStrictEqual({ ...row, kind: null, tag: null });
    } finally {
      // A failed expectation must not strand the connection for the rest of the run.
      storage.destroy();
    }
  });

  it("returns updateWhere() entities as plain objects", async () => {
    const storage = await makeStorage();
    try {
      await storage.put(row);
      const updated = await storage.updateWhere({ id: "p1" }, { value: 42 });
      expect(Object.getPrototypeOf(updated)).toBe(Object.prototype);
      expect(updated).toStrictEqual({ ...row, kind: null, tag: null, value: 42 });
    } finally {
      storage.destroy();
    }
  });
});

describe("SqliteTabularStorage join inside a transaction", () => {
  // `createTxView` runs the public `join` with `guardedRead` neutralized, so
  // the join never waits on the lock `withTransaction` holds. If that ever
  // breaks, the join waits on a lock its own caller owns and this test hangs
  // rather than failing on a value — which is why it is worth pinning on both
  // paths.
  it("runs a pushed-down join through the tx proxy without deadlocking", async () => {
    await Sqlite.init();
    const db = new Sqlite.Database(":memory:");
    const posts = new SqliteTabularStorage<typeof PostSchema, typeof PostPrimaryKeyNames>(
      db,
      `tx_posts_${uuid4().replace(/-/g, "_")}`,
      PostSchema,
      PostPrimaryKeyNames
    );
    const authors = new SqliteTabularStorage<typeof AuthorSchema, typeof AuthorPrimaryKeyNames>(
      db,
      `tx_authors_${uuid4().replace(/-/g, "_")}`,
      AuthorSchema,
      AuthorPrimaryKeyNames
    );
    await posts.setupDatabase();
    await authors.setupDatabase();
    await authors.put({ id: "a1", tenant: "t", name: "Ann", country: null });
    await posts.put({ id: "p1", tenant: "t", author_id: "a1", title: "one", views: 1 });

    const rows = await posts.withTransaction(async (tx) => {
      return await tx.join({ type: "inner", on: [{ left: "author_id", right: "id" }] }, authors);
    });

    expect(rows.map((r) => `${r.left.id}:${r.right.id}`)).toEqual(["p1:a1"]);
    posts.destroy?.();
    authors.destroy?.();
  });

  it("falls back to the hash join through the tx proxy without deadlocking", async () => {
    await Sqlite.init();
    const posts = new SqliteTabularStorage<typeof PostSchema, typeof PostPrimaryKeyNames>(
      ":memory:",
      `tx_posts_${uuid4().replace(/-/g, "_")}`,
      PostSchema,
      PostPrimaryKeyNames
    );
    // A right side on another connection forces the fallback, whose
    // leftQuery/leftGetAll re-enter this storage — through the proxy, so they
    // must reach `_queryInternal` rather than queue behind the transaction.
    const authors = new InMemoryTabularStorage<typeof AuthorSchema, typeof AuthorPrimaryKeyNames>(
      AuthorSchema,
      AuthorPrimaryKeyNames
    );
    await posts.setupDatabase();
    await authors.put({ id: "a1", tenant: "t", name: "Ann", country: null });
    await posts.put({ id: "p1", tenant: "t", author_id: "a1", title: "one", views: 1 });
    await posts.put({ id: "p2", tenant: "t", author_id: null, title: "anon", views: 2 });

    const rows = await posts.withTransaction(async (tx) => {
      return await tx.join({ type: "left", on: [{ left: "author_id", right: "id" }] }, authors);
    });

    expect(rows.map((r) => `${r.left.id}:${r.right?.id ?? "-"}`).sort()).toEqual(["p1:a1", "p2:-"]);
    posts.destroy?.();
  });
});

describe("SqliteTabularStorage join vs. an open transaction on the right side", () => {
  it("waits for a concurrent transaction instead of reading rows it rolls back", async () => {
    await Sqlite.init();
    const db = new Sqlite.Database(":memory:");
    const posts = new SqliteTabularStorage<typeof PostSchema, typeof PostPrimaryKeyNames>(
      db,
      `iso_posts_${uuid4().replace(/-/g, "_")}`,
      PostSchema,
      PostPrimaryKeyNames
    );
    const authors = new SqliteTabularStorage<typeof AuthorSchema, typeof AuthorPrimaryKeyNames>(
      db,
      `iso_authors_${uuid4().replace(/-/g, "_")}`,
      AuthorSchema,
      AuthorPrimaryKeyNames
    );
    await posts.setupDatabase();
    await authors.setupDatabase();
    await posts.put({ id: "p1", tenant: "t", author_id: "ghost", title: "one", views: 1 });

    // Both tables share one Database, so an uncommitted INSERT is visible to
    // any statement issued on that connection. The pushdown would read the
    // right table holding only the LEFT's lock and pick the row up; the join
    // must instead serialize on the right's lock and see the rolled-back state.
    let release!: () => void;
    const gate = new Promise<void>((resolve) => {
      release = resolve;
    });
    const txDone = authors
      .withTransaction(async (tx) => {
        await tx.put({ id: "ghost", tenant: "t", name: "Rolled back", country: null });
        await gate;
        throw new Error("rollback");
      })
      .catch((err: unknown) => err);

    // Let the transaction open and write before the join is issued.
    await new Promise((r) => setTimeout(r, 20));
    const joinPromise = posts.join(
      { type: "left", on: [{ left: "author_id", right: "id" }] },
      authors
    );

    release();
    expect(await txDone).toBeInstanceOf(Error);
    const joined = await joinPromise;

    expect(joined.map((r) => `${r.left.id}:${r.right?.id ?? "-"}`)).toEqual(["p1:-"]);
    expect(await authors.get({ id: "ghost" })).toBeUndefined();
    posts.destroy?.();
    authors.destroy?.();
  });
});

