/** Controls how client-provided values for auto-generated keys are handled. */
export type ClientProvidedKeysOption = "never" | "if-missing" | "always";

export type KeyGenerationStrategy = "autoincrement" | "uuid";

/**
 * Abstract base class for tabular storage repositories. Splits a schema into
 * primary-key and value halves, manages indexes and `x-auto-generated` PK
 * columns, and emits {@link TabularEventListeners} events for all reads and
 * mutations.
 */
export abstract class BaseTabularStorage<
  Schema extends DataPortSchemaObject,
  PrimaryKeyNames extends ReadonlyArray<keyof Schema["properties"]>,
  // computed types
  Entity = FromSchema<Schema, TypedArraySchemaOptions>,
  PrimaryKey = SimplifyPrimaryKey<Entity, PrimaryKeyNames>,
  Value = Omit<Entity, PrimaryKeyNames[number] & keyof Entity>,
  InsertType = InsertEntity<Entity, AutoGeneratedKeys<Schema>>,
> implements ITabularStorage<Schema, PrimaryKeyNames, Entity, PrimaryKey, InsertType> {
  protected events = new EventEmitter<TabularEventListeners<PrimaryKey, Entity>>();

  protected indexes: Array<keyof Entity>[];
  /**
   * Compound column tuples that must each be unique across all rows in the
   * table. Concrete backends translate these into DB-level UNIQUE indexes
   * (SQLite / Postgres `CREATE UNIQUE INDEX IF NOT EXISTS`) so the
   * deduplication invariant survives outside the application-layer code that
   * upserts canonical rows. Stored separately from {@link indexes} so the
   * prefix-redundancy filter applied to plain indexes does not collapse a
   * unique tuple that happens to share a prefix.
   */
  protected uniqueIndexes: Array<keyof Entity>[];
  protected primaryKeySchema: DataPortSchemaObject;
  protected valueSchema: DataPortSchemaObject;

  /**
   * Optional declarative migrations evolving older deployments to the
   * current target schema. When set + non-empty, `setupDatabase()` on
   * concrete subclasses delegates to {@link applyTabularMigrations}.
   */
  protected readonly tabularMigrations: ReadonlyArray<ITabularMigration> | undefined;

  /**
   * Default component name used when an `ITabularMigration.component` is
   * omitted. Defaults to `tabular:${storageName}` once the subclass has
   * supplied a name.
   */
  protected migrationComponent: string = "tabular:unnamed";

  /** At most one primary-key column may be marked `x-auto-generated: true`. */
  protected autoGeneratedKeyName: keyof Entity | null = null;
  protected autoGeneratedKeyStrategy: KeyGenerationStrategy | null = null;
  protected clientProvidedKeys: ClientProvidedKeysOption;

  constructor(
    protected schema: Schema,
    protected primaryKeyNames: PrimaryKeyNames,
    indexes: readonly (keyof NoInfer<Entity> | readonly (keyof NoInfer<Entity>)[])[] = [],
    clientProvidedKeys: ClientProvidedKeysOption = "if-missing",
    tabularMigrations?: ReadonlyArray<ITabularMigration>,
    migrationName?: string,
    uniqueIndexes: readonly (readonly (keyof NoInfer<Entity>)[])[] = []
  ) {
    this.tabularMigrations = tabularMigrations;
    if (migrationName) {
      this.migrationComponent = `tabular:${migrationName}`;
    }
    this.clientProvidedKeys = clientProvidedKeys;

    const split = splitSchemaByPrimaryKey(schema, primaryKeyNames);
    this.primaryKeySchema = split.primaryKeySchema;
    this.valueSchema = split.valueSchema;

    assertValidColumnNames([...this.primaryKeyColumns(), ...this.valueColumns()]);

    this.indexes = toIndexTuples<Entity>(indexes);

    // Drop any compound index that is a prefix of another compound index or
    // of the primary key — it's redundant for lookups.
    this.indexes = this.filterCompoundKeys(
      this.primaryKeyColumns() as unknown as Array<keyof Entity>,
      this.indexes
    );

    assertIndexColumnsInSchema(this.indexes, this.primaryKeySchema, this.valueSchema);

    // Validate unique index column names against the schema the same way
    // `indexes` are validated. NULL semantics and DDL emission live in the
    // concrete backends.
    this.uniqueIndexes = normalizeUniqueIndexes<Entity>(
      uniqueIndexes,
      this.primaryKeySchema,
      this.valueSchema
    );

    this.indexes = dropIndexesCoveredByUnique(this.indexes, this.uniqueIndexes);

    const autoGenKeyName = detectAutoGeneratedKey(schema, primaryKeyNames);
    if (autoGenKeyName !== null) {
      this.autoGeneratedKeyName = autoGenKeyName as keyof Entity;
      this.autoGeneratedKeyStrategy = this.determineGenerationStrategy(
        autoGenKeyName,
        schema.properties[autoGenKeyName as keyof Schema["properties"]]
      );
    }
  }

  protected filterCompoundKeys(
    primaryKey: Array<keyof Entity>,
    potentialKeys: Array<keyof Entity>[]
  ): Array<keyof Entity>[] {
    return filterCompoundKeys(primaryKey, potentialKeys);
  }

  on<Event extends TabularEventName>(
    name: Event,
    fn: TabularEventListener<Event, PrimaryKey, Entity>
  ) {
    this.events.on(name, fn);
  }

  off<Event extends TabularEventName>(
    name: Event,
    fn: TabularEventListener<Event, PrimaryKey, Entity>
  ) {
    this.events.off(name, fn);
  }

  once<Event extends TabularEventName>(
    name: Event,
    fn: TabularEventListener<Event, PrimaryKey, Entity>
  ) {
    this.events.once(name, fn);
  }

  emit<Event extends TabularEventName>(
    name: Event,
    ...args: TabularEventParameters<Event, PrimaryKey, Entity>
  ) {
    this.events.emit(name, ...args);
  }

  waitOn<Event extends TabularEventName>(
    name: Event
  ): Promise<TabularEventParameters<Event, PrimaryKey, Entity>> {
    return this.events.waitOn(name) as Promise<TabularEventParameters<Event, PrimaryKey, Entity>>;
  }

  /**
   * Emits a `put` that has already cleared deferral, bypassing an `emitPut`
   * override that would re-queue it. This is how a connection-scoped
   * transaction drains a participant's post-commit queue.
   *
   * Public only because the draining code lives outside the class hierarchy —
   * a transaction flushes every PARTICIPANT, not just itself, so a `protected`
   * method would be unreachable. Nothing else should call it: emitting a `put`
   * for a row that has not committed is exactly what the deferral exists to
   * prevent.
   *
   * @internal
   */
  emitCommittedPut(entity: Entity): void {
    safeEmit(this.events, "put", entity);
  }

  abstract put(value: InsertType): Promise<Entity>;
  abstract putBulk(values: InsertType[]): Promise<Entity[]>;
  abstract get(key: PrimaryKey): Promise<Entity | undefined>;
  abstract delete(key: PrimaryKey | Entity): Promise<void>;
  abstract getAll(options?: QueryOptions<Entity>): Promise<Entity[] | undefined>;
  abstract deleteAll(): Promise<void>;
  abstract size(): Promise<number>;

  /**
   * Default plural-get implementation: parallel single-key fetches via
   * {@link get}, with `undefined` results filtered out. Backends with a
   * cheaper batched path (SQL `WHERE pk IN (...)`) override this.
   */
  async getBulk(keys: readonly PrimaryKey[]): Promise<Entity[]> {
    if (keys.length === 0) return [];
    const results = await Promise.all(keys.map((k) => this.get(k)));
    const found = results.filter((r) => r !== undefined) as Entity[];
    safeEmit(this.events, "getBulk", keys, found);
    return found;
  }

  /** Concrete storage implementations can override this with native count APIs. */
  async count(criteria?: SearchCriteria<Entity>): Promise<number> {
    if (!criteria || Object.keys(criteria).length === 0) {
      return await this.size();
    }
    const entities = await this.query(criteria);
    return entities?.length ?? 0;
  }

  abstract deleteSearch(criteria: DeleteSearchCriteria<Entity>): Promise<void>;

  abstract updateWhere(
    match: SearchCriteria<Entity>,
    patch: Partial<Entity>
  ): Promise<Entity | undefined>;

  abstract query(
    criteria: SearchCriteria<Entity>,
    options?: QueryOptions<Entity>
  ): Promise<Entity[] | undefined>;

  /**
   * Strict, projected query served entirely by a covering compound index.
   * Subclasses that support index-only reads (e.g. IndexedDB, InMemory) should
   * override this with an efficient implementation. The default throws
   * {@link CoveringIndexMissingError} so callers get a consistent error when
   * the storage backend has not implemented index-only projection.
   */
  queryIndex<K extends keyof Entity & string>(
    criteria: SearchCriteria<Entity>,
    options: CoveringIndexQueryOptions<Entity, K>
  ): Promise<Pick<Entity, K>[]> {
    this.validateSelect(options);
    const requiredColumns = [
      ...Object.keys(criteria),
      ...(options.orderBy ?? []).map((o) => String(o.column)),
      ...options.select.map(String),
    ];
    throw new CoveringIndexMissingError(this.constructor.name, requiredColumns, []);
  }

  /**
   * Default join: an application-side hash join over `query` and the `in`
   * criterion (see {@link runHashJoin}). Every backend inherits it; the SQL
   * backends override it with a single `JOIN` statement when both tables sit
   * on one connection. The callbacks are bound to `this`, so a subclass's own
   * `query` / `getAll` (mutex, transaction routing) still runs underneath.
   *
   * The right side is unwrapped through any chain of delegating wrappers
   * ({@link resolveJoinDelegate}) before anything reads it, so a join whose
   * left side is a plain storage and whose right side is wrapped still reads
   * both halves from the same place. A wrapper that must stay in the path —
   * one that scopes what the join may see — does not delegate, and survives.
   */
  async join<R, T extends JoinType>(
    spec: JoinSpec<Entity, R, T>,
    right: ITabularStorage<any, any, R, any, any>
  ): Promise<JoinedRow<Entity, R, T>[]> {
    const target = resolveJoinDelegate(right) as ITabularStorage<any, any, R, any, any>;
    this.validateJoinSpec(spec, target);
    return runHashJoin<Entity, R, T>(
      {
        leftQuery: (criteria, options) => this.query(criteria, options),
        leftGetAll: (options) => this.getAll(options),
        rightQuery: (criteria) => target.query(criteria),
        leftColumnIsNullable: (column) => this.columnIsNullable(column),
      },
      spec
    );
  }

  /**
   * Whether `column` may hold null — either it is absent from `required` or
   * its schema admits the null type.
   */
  protected columnIsNullable(column: string): boolean {
    const typeDef = this.schema.properties[column];
    if (typeDef === undefined) return true;
    const required = this.schema.required;
    if (!Array.isArray(required) || !required.includes(column)) return true;
    return isNullableSchema(typeDef);
  }

  /**
   * Validates a join spec against this schema and, when the right storage
   * exposes one, against its schema too.
   */
  protected validateJoinSpec<R>(
    spec: JoinSpec<Entity, R>,
    right: ITabularStorage<any, any, R, any, any>
  ): void {
    const rightProperties =
      right instanceof BaseTabularStorage
        ? (right.schema.properties as Record<string, unknown>)
        : undefined;
    validateJoinSpec(this.schema.properties as Record<string, unknown>, rightProperties, spec);
  }

  abstract getOffsetPage(offset: number, limit: number): Promise<Entity[] | undefined>;

  /** Cursor-based iteration, stable under concurrent writes. */
  async *records(pageSize: number = 100): AsyncGenerator<Entity, void, undefined> {
    if (pageSize <= 0) {
      throw new RangeError(`pageSize must be greater than 0, got ${pageSize}`);
    }
    let cursor: PageCursor | undefined;
    while (true) {
      const page = await this.getPage({ limit: pageSize, cursor });
      for (const entity of page.items) {
        yield entity;
      }
      if (!page.nextCursor || page.items.length === 0) break;
      cursor = page.nextCursor;
    }
  }

  /**
   * Cursor-based iteration, stable under concurrent writes. Each yielded
   * array is a fresh copy of `Page.items` so callers can mutate it safely.
   */
  async *pages(pageSize: number = 100): AsyncGenerator<Entity[], void, undefined> {
    if (pageSize <= 0) {
      throw new RangeError(`pageSize must be greater than 0, got ${pageSize}`);
    }
    let cursor: PageCursor | undefined;
    while (true) {
      const page = await this.getPage({ limit: pageSize, cursor });
      if (page.items.length > 0) {
        yield page.items.slice() as Entity[];
      }
      if (!page.nextCursor || page.items.length === 0) break;
      cursor = page.nextCursor;
    }
  }

  /**
   * Default keyset-pagination implementation. Backends that can express
   * tuple comparison natively (SQL row-value comparisons) should override
   * this for efficiency, but the default works against any implementation
   * of {@link query} / {@link getAll}.
   */
  async getPage(request: PageRequest<Entity> = {}): Promise<Page<Entity>> {
    return this.runPage(undefined, request);
  }

  /** Default cursor-paginated form of {@link query}. */
  async queryPage(
    criteria: SearchCriteria<Entity>,
    request: PageRequest<Entity> = {}
  ): Promise<Page<Entity>> {
    return this.runPage(criteria, request);
  }

  /**
   * Shared keyset-pagination engine for both {@link getPage} and
   * {@link queryPage}. Translates the cursor into AND criteria using the
   * primary key column(s) and runs the existing {@link query}/{@link getAll}
   * machinery, then re-encodes the position of the last returned row.
   *
   * For composite primary keys this performs the keyset comparison in
   * memory after fetching a candidate window. SQL backends should override
   * {@link getPage}/{@link queryPage} to push it down to the database.
   *
   * Every step the engine needs is handed over bound to `this`, so a
   * subclass override of `query`, `getAll`, `sortInMemory` (and the rest)
   * still takes effect.
   */
  protected async runPage(
    criteria: SearchCriteria<Entity> | undefined,
    request: PageRequest<Entity>
  ): Promise<Page<Entity>> {
    const deps: KeysetPageDeps<Entity> = {
      validatePageRequest: (pageRequest) => this.validatePageRequest(pageRequest),
      primaryKeyColumns: () => this.primaryKeyColumns() as unknown as Array<keyof Entity>,
      buildEffectiveOrderBy: (orderBy, pkColumns) => this.buildEffectiveOrderBy(orderBy, pkColumns),
      sortInMemory: (rows, orderBy) => this.sortInMemory(rows, orderBy),
      applyKeysetFilter: (rows, cursor, effectiveOrderBy, pkColumns) =>
        this.applyKeysetFilter(rows, cursor, effectiveOrderBy, pkColumns),
      buildCursor: (row, effectiveOrderBy) => this.buildCursor(row, effectiveOrderBy),
      getAll: (options) => this.getAll(options),
      query: (queryCriteria, options) => this.query(queryCriteria, options),
    };
    return runKeysetPage<Entity>(deps, criteria, request);
  }

  /**
   * Returns the order spec actually used to drive a keyset page: the
   * caller's `orderBy` (if any) followed by every primary-key column as a
   * stable tiebreaker. PK columns are appended in ASC direction unless the
   * caller already specified a direction for them.
   */
  protected buildEffectiveOrderBy(
    orderBy: ReadonlyArray<OrderBy<Entity>> | undefined,
    pkColumns: ReadonlyArray<keyof Entity>
  ): ReadonlyArray<OrderBy<Entity>> {
    return buildEffectiveOrderBy(orderBy, pkColumns);
  }

  /**
   * Sorts rows in place by the given order spec, using the same null-first
   * comparison rules as the cursor filter so results are consistent.
   */
  protected sortInMemory(rows: Entity[], orderBy: ReadonlyArray<OrderBy<Entity>>): Entity[] {
    return sortInMemory(rows, orderBy);
  }

  /**
   * In-memory keyset filter: drops rows that come at or before the cursor
   * row according to `orderBy + primaryKey`. Used by the default
   * implementation when the backend can't express tuple comparison.
   */
  protected applyKeysetFilter(
    rows: Entity[],
    cursor: CursorPayload,
    effectiveOrderBy: ReadonlyArray<OrderBy<Entity>>,
    _pkColumns: ReadonlyArray<keyof Entity>
  ): Entity[] {
    return applyKeysetFilter(rows, cursor, effectiveOrderBy);
  }

  /**
   * Encodes the position of `row` as an opaque cursor. The caller passes
   * the effective ordering it just used — caller-supplied `orderBy`
   * followed by any primary-key columns not already covered by `orderBy`
   * — and this writes one value per effective column, in the same order.
   * Computing that ordering is the caller's responsibility because they
   * already have it in hand and we don't want to recompute it here.
   */
  protected buildCursor(row: Entity, effectiveOrderBy: ReadonlyArray<OrderBy<Entity>>): PageCursor {
    return buildCursor(row, effectiveOrderBy);
  }

  /** Default throws — override in subclasses that support subscriptions. */
  public subscribeToChanges(
    _callback: (change: TabularChangePayload<Entity>) => void,
    _options?: TabularSubscribeOptions
  ): () => void {
    throw new Error(
      `subscribeToChanges is not implemented for ${this.constructor.name}. ` +
        `All concrete repository implementations should override this method.`
    );
  }

  /**
   * Validates query parameters: criteria columns, options, and operator values.
   * @throws StorageEmptyCriteriaError if criteria is empty
   * @throws StorageInvalidLimitError if limit <= 0
   * @throws StorageValidationError if offset < 0
   * @throws StorageInvalidColumnError if any column name is not in the schema
   */
  protected validateQueryParams(
    criteria: SearchCriteria<Entity>,
    options?: QueryOptions<Entity>
  ): void {
    validateQueryParams(this.schema.properties, criteria, options, (orderBy) =>
      this.validateOrderBy(orderBy)
    );
  }

  protected validateGetAllOptions(options?: QueryOptions<Entity>): void {
    validateGetAllOptions(options, (orderBy) => this.validateOrderBy(orderBy));
  }

  /**
   * The first line of every backend's `deleteSearch`: false when there is
   * nothing to do, a throw when the criteria would take the whole table.
   * See {@link shouldRunDeleteSearch}.
   */
  protected shouldRunDeleteSearch(criteria: DeleteSearchCriteria<Entity>): boolean {
    return shouldRunDeleteSearch(criteria);
  }

  /**
   * Whether `criteria` name no row, for the backends that would otherwise ask
   * a peer a question the wire cannot carry. See {@link criteriaMatchNoRow}.
   */
  protected criteriaMatchNoRow(criteria: DeleteSearchCriteria<Entity> | undefined): boolean {
    return criteriaMatchNoRow(criteria);
  }

  /**
   * Validates the `orderBy` clause of a {@link PageRequest}: column names
   * must exist in the schema and directions must be `"ASC"` or `"DESC"`.
   *
   * Page paths (`getPage`/`queryPage`) must call this before any backend
   * builds SQL, because column names from `request.orderBy` end up
   * interpolated directly into `ORDER BY` and the keyset `WHERE` clauses.
   * Without this guard a caller passing arbitrary strings would either
   * trigger a backend SQL error or, worse, allow SQL injection on backends
   * that emit unquoted identifiers.
   */
  protected validateOrderBy(orderBy: ReadonlyArray<OrderBy<Entity>> | undefined): void {
    validateOrderBy(this.schema.properties, orderBy);
  }

  /**
   * Validates the components of a cursor-paginated request that are about
   * to be used to build a query. Centralises the schema-level guarantees
   * that `runPage`/`runSqlPage`/Supabase's `runSupabasePage` all rely on
   * before they interpolate column names into SQL or PostgREST filters.
   */
  protected validatePageRequest(request: PageRequest<Entity>): void {
    validatePageRequest(request, (orderBy) => this.validateOrderBy(orderBy));
  }

  /**
   * Validates the `select` array in a {@link CoveringIndexQueryOptions}.
   * Throws {@link StorageValidationError} when `select` is empty or contains
   * a column that is not in the schema's `properties`.
   */
  protected validateSelect<K extends keyof Entity & string>(
    options: CoveringIndexQueryOptions<Entity, K>
  ): void {
    validateSelect<Entity, K>(this.schema.properties, options);
  }

  protected primaryKeyColumns(): Array<keyof PrimaryKey> {
    const columns: Array<keyof PrimaryKey> = [];
    for (const key of Object.keys(this.primaryKeySchema.properties)) {
      columns.push(key as keyof PrimaryKey);
    }
    return columns;
  }

  /**
   * Guards {@link ITabularStorage.updateWhere}: a patch must not include a
   * primary-key column. `updateWhere` updates a single matched row in place;
   * changing its identity is a delete+insert, not an update, and moving the row
   * would orphan the old key on the read-modify-write backends. Callers patch
   * non-key columns and select the row via `match`.
   */
  protected assertPatchKeepsPrimaryKey(patch: Partial<Entity>): void {
    const record = patch as Record<string, unknown>;
    for (const col of this.primaryKeyColumns()) {
      if (record[String(col)] !== undefined) {
        throw new StorageValidationError(
          `updateWhere patch must not include primary-key column "${String(col)}"`
        );
      }
    }
  }

  protected valueColumns(): Array<keyof Value> {
    const columns: Array<keyof Value> = [];
    for (const key of Object.keys(this.valueSchema.properties)) {
      columns.push(key as keyof Value);
    }
    return columns;
  }

  /**
   * The identity emitted on the `delete` event for a bulk `deleteSearch`: the
   * plain (operator-free) columns of the criteria — which include the owner /
   * scope columns — as a `Partial<Entity>`. Search conditions are dropped since
   * they don't identify a concrete value.
   */
  protected deleteIdentity(criteria: DeleteSearchCriteria<Entity>): Partial<Entity> {
    return deleteSearchIdentity(criteria);
  }

  protected separateKeyValueFromCombined(obj: Entity): { value: Value; key: PrimaryKey } {
    if (obj === null) {
      console.warn("Key is null");
      return { value: {} as Value, key: {} as PrimaryKey };
    }
    if (typeof obj !== "object") {
      console.warn("Object is not an object");
      return { value: {} as Value, key: {} as PrimaryKey };
    }
    const primaryKeyNames = this.primaryKeyColumns();
    const valueNames = this.valueColumns();
    const value: Partial<Value> = {};
    const key: Partial<PrimaryKey> = {};
    const objRecord = obj as Record<string, unknown>;
    for (const k of primaryKeyNames) {
      (key as Record<string, unknown>)[k as string] = objRecord[k as string];
    }
    for (const k of valueNames) {
      (value as Record<string, unknown>)[k as string] = objRecord[k as string];
    }

    return { value: value as Value, key: key as PrimaryKey };
  }

  protected async getKeyAsIdString(key: PrimaryKey): Promise<string> {
    return await makeFingerprint(key);
  }

  /** Returns key values ordered to match the schema's primary-key declaration. */
  protected getPrimaryKeyAsOrderedArray(key: PrimaryKey): ValueOptionType[] {
    const orderedParams: ValueOptionType[] = [];
    const keyObj = key as Record<string, ValueOptionType>;
    for (const k in this.primaryKeySchema.properties) {
      if (k in keyObj) {
        orderedParams.push(keyObj[k]);
      } else {
        throw new Error(`Missing required primary key field: ${k}`);
      }
    }
    return orderedParams;
  }

  public findBestMatchingIndex(
    unorderedSearchKey: Array<keyof Entity>
  ): Array<keyof Entity> | undefined {
    if (!unorderedSearchKey.length) return undefined;

    const allKeys: Array<keyof Entity>[] = [
      this.primaryKeyColumns() as unknown as Array<keyof Entity>,
      ...(this.indexes as Array<keyof Entity>[]),
    ];

    const searchKeySet = new Set(unorderedSearchKey);

    const hasMatchingPrefix = (index: Array<keyof Entity>): boolean => {
      return index.length > 0 && searchKeySet.has(index[0]);
    };

    let bestMatch: Array<keyof Entity> | undefined;
    let bestMatchScore = 0;

    for (const index of allKeys) {
      if (hasMatchingPrefix(index)) {
        let score = 0;
        for (const col of index) {
          if (!searchKeySet.has(col)) break;
          score++;
        }

        if (score > bestMatchScore) {
          bestMatch = index;
          bestMatchScore = score;
        }
      }
    }

    return bestMatch;
  }

  protected hasAutoGeneratedKey(): boolean {
    return this.autoGeneratedKeyName !== null;
  }

  protected isAutoGeneratedKey(name: string): boolean {
    return this.autoGeneratedKeyName !== null && String(this.autoGeneratedKeyName) === name;
  }

  protected determineGenerationStrategy(columnName: string, typeDef: any): KeyGenerationStrategy {
    return determineGenerationStrategy(columnName, typeDef);
  }

  /**
   * Generates a key value for client-side key generation. Override in storage
   * classes that generate keys client-side (InMemory, IndexedDB for UUIDs).
   * SQL-based storages typically generate keys server-side.
   */
  protected generateKeyValue(
    columnName: string,
    strategy: KeyGenerationStrategy
  ): Promise<string | number> | string | number {
    throw new Error(
      `generateKeyValue not implemented for ${this.constructor.name}. ` +
        `Column: ${columnName}, Strategy: ${strategy}`
    );
  }

  /**
   * Runs `fn` inside a transaction. The default implementation provides no
   * rollback semantics — it simply invokes `fn(this)`. Concrete subclasses
   * with native transaction support (SQLite, PostgreSQL) override this.
   */
  async withTransaction<T>(fn: (tx: this) => Promise<T>): Promise<T> {
    return await fn(this);
  }

  /**
   * Subclass override returning a backend-specific applier. Returning `null`
   * disables tabular migrations for the storage. The base class returns
   * `null`; only backends that have wired up their applier override this.
   */
  public getMigrationApplier(): ITabularMigrationApplier | null {
    return null;
  }

  /**
   * Runs `this.tabularMigrations` through the orchestrator using the
   * backend-supplied applier. Idempotent (no-op when no migrations are
   * declared, or when all are already applied).
   */
  protected async applyTabularMigrations(options?: RunTabularMigrationsOptions): Promise<void> {
    if (!this.tabularMigrations || this.tabularMigrations.length === 0) return;
    const applier = this.getMigrationApplier();
    if (!applier) {
      throw new Error(
        `${this.constructor.name} declared migrations but has no migration applier wired up.`
      );
    }
    await runTabularMigrations(applier, this.migrationComponent, this.tabularMigrations, options);
  }

  /**
   * Must be called before using any other methods (except for in-memory
   * implementations). Default is a no-op; override in subclasses that need setup.
   */
  async setupDatabase(): Promise<void> {}

  destroy(): void {}

  async [Symbol.asyncDispose](): Promise<void> {
    this.destroy();
  }

  [Symbol.dispose](): void {
    this.destroy();
  }
}
