  /** Bulk-insert dialect for the shared {@link runBulkPut} engine. */
  private sqliteBulkDialect(): BulkPutDialect {
    const q = "`";
    const table = this.table;
    const useUpsert = this.uniqueIndexes.length > 0;
    const pkColumns = this.primaryKeyColumns() as unknown as string[];
    return {
      quote: q,
      placeholder: () => "?",
      insertInto: (cols) =>
        useUpsert
          ? `INSERT INTO ${q}${table}${q} (${cols})`
          : `INSERT OR REPLACE INTO ${q}${table}${q} (${cols})`,
      conflictClause: (insertColumns) => {
        if (!useUpsert) return "";
        const pkList = pkColumns.map((c) => `${q}${c}${q}`).join(", ");
        const nonPk = insertColumns.filter((c) => !pkColumns.includes(c));
        const assignments = (nonPk.length > 0 ? nonPk : pkColumns)
          .map((c) => `${q}${c}${q} = excluded.${q}${c}${q}`)
          .join(", ");
        return `ON CONFLICT(${pkList}) DO UPDATE SET ${assignments}`;
      },
      mintUuidClientSide: true,
    };
  }

  protected override sqlJoinDialect(): SqlJoinDialect {
    return {
      dialect: SqliteDialect,
      executeRaw: async (sql, params) =>
        this.db.prepare(sql).all(...params) as Record<string, unknown>[],
    };
  }

  private sqliteDialect() {
    return {
      quote: "`",
      // SQLite uses positional `?` placeholders so the index is intentionally
      // unused. If a future contributor needs numbered placeholders (SQLite
      // does support `?N`), update both the placeholder and any callers
      // sharing the running paramIdx counter.
      placeholder: (_index: number) => "?",
      buildSearchWhere: (
        criteria: SearchCriteria<Entity>,
        startIndex: number
      ): { whereClause: string; params: ValueOptionType[]; nextIndex: number } => {
        const { whereClause, params } = this.buildDeleteSearchWhere(criteria);
        return { whereClause, params, nextIndex: startIndex + params.length };
      },
      executeSelect: async (sql: string, params: ValueOptionType[]): Promise<Entity[]> => {
        const stmt = this.db.prepare(sql);
        const rows = stmt.all(...params) as Entity[];
        for (const row of rows) {
          const record = row as Record<string, unknown>;
          for (const k in this.schema.properties) {
            record[k] = this.sqlToJsValue(k, record[k] as ValueOptionType);
          }
        }
        return rows;
      },
    };
  }

